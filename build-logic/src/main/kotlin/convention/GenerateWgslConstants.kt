package convention

import org.gradle.api.DefaultTask
import org.gradle.api.file.DirectoryProperty
import org.gradle.api.file.FileVisitDetails
import org.gradle.api.provider.Property
import org.gradle.api.tasks.CacheableTask
import org.gradle.api.tasks.IgnoreEmptyDirectories
import org.gradle.api.tasks.Input
import org.gradle.api.tasks.InputFiles
import org.gradle.api.tasks.OutputDirectory
import org.gradle.api.tasks.PathSensitive
import org.gradle.api.tasks.PathSensitivity
import org.gradle.api.tasks.SkipWhenEmpty
import org.gradle.api.tasks.TaskAction
import java.io.File

/**
 * Generates an `internal const val` for each WGSL file in [shaderDirectory],
 * named after its path, so `post/pastel.wgsl` becomes `POST_PASTEL_WGSL`.
 */
@CacheableTask
public abstract class GenerateWgslConstants : DefaultTask() {
  /** The directory whose WGSL files are embedded. */
  @get:InputFiles
  @get:SkipWhenEmpty
  @get:IgnoreEmptyDirectories
  @get:PathSensitive(PathSensitivity.RELATIVE)
  public abstract val shaderDirectory: DirectoryProperty

  /** The package of the generated constants. */
  @get:Input
  public abstract val packageName: Property<String>

  /** The directory the Kotlin sources are generated into. */
  @get:OutputDirectory
  public abstract val outputDirectory: DirectoryProperty

  /** Replaces the generated sources with ones for the current shaders. */
  @TaskAction
  public fun generate(): Unit =
    generateImpl()

  // region internal

  private fun generateImpl() {
    val output = outputDirectory.get().asFile
    output.deleteRecursively()
    output.mkdirs()
    shaderDirectory.asFileTree
      .matching { include("**/*.wgsl") }
      .visit { if (!isDirectory) writeConstant(this, output) }
  }

  private fun writeConstant(
    shader: FileVisitDetails,
    output: File,
  ) {
    val path = shader.relativePath.pathString
    val name = constantName(path)
    val literals =
      shader.file
        .readLines()
        .map(::literal)
        .ifEmpty { listOf("\"\"") }
        .joinToString(" +\n    ")
    output.resolve("$name.kt").writeText(
      """
      |// Generated by convention.wgsl from $path
      |package ${packageName.get()}
      |
      |internal const val $name: String =
      |  $literals
      |
      """.trimMargin(),
    )
  }

  // endregion
}

// region internal

// Turns a path like post/pastelTint.wgsl into POST_PASTEL_TINT_WGSL
private fun constantName(
  path: String,
): String =
  path
    .replace(Regex("([a-z0-9])([A-Z])"), "$1_$2")
    .replace(Regex("[^A-Za-z0-9]+"), "_")
    .uppercase()

// Quotes line as a Kotlin string literal that ends with a newline
private fun literal(
  line: String,
): String =
  """"${escape(line)}\n""""

private fun escape(
  line: String,
): String =
  line
    .replace("\\", "\\\\")
    .replace("\"", "\\\"")
    .replace("$", "\\$")

// endregion
